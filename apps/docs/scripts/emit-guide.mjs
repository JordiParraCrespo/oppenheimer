#!/usr/bin/env node
/**
 * Write the guide's pages into `@oppenheimer/shared/guide`.
 *
 * `docs/guide/*.md` is the one copy of "Using Oppenheimer": the docs site
 * publishes it, and every bot reads the same pages through its
 * `read_oppenheimer_docs` tool, so a bot knows the product as it is in the
 * version the API runs, with no docs site to reach (`product/versions/mvp/25-bots.md`
 * §4.1, "Oppenheimer's own guide"). The API cannot read this app's files at
 * run time, so the pages are generated into the shared package, the way
 * `generate:api-client` writes the client, and committed.
 *
 *   node scripts/emit-guide.mjs          write the module
 *   node scripts/emit-guide.mjs --check  fail when the committed module is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readGuidePages } from './guide-pages.mjs';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const outputPath = join(repoRoot, 'packages', 'shared', 'src', 'guide', 'guide-pages.gen.ts');

function render() {
  const pages = readGuidePages();
  const entries = pages.flatMap((page) => [
    '  {',
    `    id: ${JSON.stringify(page.id)},`,
    `    title: ${JSON.stringify(page.title)},`,
    `    description: ${JSON.stringify(page.description)},`,
    `    body: ${JSON.stringify(page.body)},`,
    '  },',
  ]);
  return [
    '// Code generated by apps/docs/scripts/emit-guide.mjs from apps/docs/docs/guide;',
    '// DO NOT EDIT. Edit the pages there, then run `pnpm generate:guide`.',
    '',
    "import type { GuidePage } from './guide-page.js';",
    '',
    "/** The guide's pages, in the order the docs site lists them. */",
    'export const GUIDE_PAGES: readonly GuidePage[] = [',
    ...entries,
    '];',
    '',
  ].join('\n');
}

const check = process.argv.includes('--check');
const wanted = render();
const where = relative(repoRoot, outputPath);
if (check) {
  let current = '';
  try {
    current = readFileSync(outputPath, 'utf8');
  } catch {}
  if (current !== wanted) {
    console.error(`${where} is not what docs/guide generates. Run \`pnpm generate:guide\`.`);
    process.exit(1);
  }
  console.log(`${where} is current.`);
} else {
  writeFileSync(outputPath, wanted);
  console.log(`Wrote ${where}.`);
}
