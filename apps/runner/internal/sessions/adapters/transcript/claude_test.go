package transcript_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"

	"github.com/jordiparracrespo/oppenheimer/apps/runner/internal/sessions/adapters/transcript"
	"github.com/jordiparracrespo/oppenheimer/apps/runner/internal/sessions/domain"
)

const conversation = "3f1c2b8e-4a5d-4c6e-9f70-1a2b3c4d5e6f"

// Lines as Claude Code writes them, trimmed to the fields the reader looks at
// plus a few it must ignore.
const (
	snapshotLine = `{"type":"file-history-snapshot","messageId":"m-0","snapshot":{}}`
	caveatLine   = `{"type":"user","isMeta":true,"message":{"role":"user","content":"Caveat: The messages below were generated by the user while running local commands."}}`
	clearLine    = `{"type":"user","message":{"role":"user","content":"<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>"}}`
	stdoutLine   = `{"type":"user","message":{"role":"user","content":"<local-command-stdout></local-command-stdout>"}}`
	promptLine   = `{"parentUuid":null,"isSidechain":false,"userType":"external","cwd":"/w/sessions/bold-otter-3f9a7k/oppenheimer","sessionId":"` + conversation + `","type":"user","message":{"role":"user","content":"Fix the repo picker so it lists archived repos"},"uuid":"u-1"}`
	answerLine   = `{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"Looking."}]}}`
)

// write puts a transcript where Claude Code keeps it: a folder named after the
// working directory, a file named after the conversation.
func write(t *testing.T, lines ...string) string {
	t.Helper()
	projects := t.TempDir()
	dir := filepath.Join(projects, "-w-sessions-bold-otter-3f9a7k-oppenheimer")
	if err := os.MkdirAll(dir, 0o700); err != nil {
		t.Fatal(err)
	}
	body := strings.Join(lines, "\n")
	if len(lines) > 0 {
		body += "\n"
	}
	if err := os.WriteFile(filepath.Join(dir, conversation+".jsonl"), []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
	return projects
}

func firstPrompt(projects string) string {
	return transcript.New(transcript.Options{ClaudeProjects: projects}).FirstPrompt(domain.AgentClaude, conversation)
}

func TestTheFirstMessageIsWhatThePersonTyped(t *testing.T) {
	projects := write(t, snapshotLine, caveatLine, clearLine, stdoutLine, promptLine, answerLine,
		`{"type":"user","message":{"role":"user","content":"and the second message is not the first"}}`)
	if got, want := firstPrompt(projects), "Fix the repo picker so it lists archived repos"; got != want {
		t.Fatalf("first prompt = %q, want %q", got, want)
	}
}

func TestAMessageWithAnImageIsItsText(t *testing.T) {
	projects := write(t, `{"type":"user","message":{"role":"user","content":[`+
		`{"type":"image","source":{"type":"base64","media_type":"image/png","data":"iVBORw0KGgo="}},`+
		`{"type":"text","text":"Match this mockup"}]}}`)
	if got := firstPrompt(projects); got != "Match this mockup" {
		t.Fatalf("first prompt = %q, want the text block", got)
	}
}

func TestASlashCommandWithArgumentsReadsAsTyped(t *testing.T) {
	projects := write(t, `{"type":"user","message":{"role":"user","content":"<command-message>review</command-message>\n<command-name>/review</command-name>\n<command-args>the auth module</command-args>"}}`)
	if got := firstPrompt(projects); got != "/review the auth module" {
		t.Fatalf("first prompt = %q, want the command as typed", got)
	}
}

// What is not the person's first message never names the session: a tool's
// result, a subagent's conversation, a compaction summary, a background
// task's end.
func TestTheAgentsOwnLinesAreNotAPrompt(t *testing.T) {
	projects := write(t,
		`{"type":"user","message":{"role":"user","content":[{"type":"tool_result","tool_use_id":"t-1","content":"ok"}]}}`,
		`{"type":"user","isSidechain":true,"message":{"role":"user","content":"Search the codebase for the picker"}}`,
		`{"type":"user","isCompactSummary":true,"message":{"role":"user","content":"This session is being continued"}}`,
		`{"type":"user","message":{"role":"user","content":"<task-notification>\n<status>completed</status>\n<summary>Background command \"Wait\" completed</summary>\n</task-notification>"}}`,
	)
	if got := firstPrompt(projects); got != "" {
		t.Fatalf("first prompt = %q, want none", got)
	}
}

// Claude Code appends as it goes, so the last line may be half written; it is
// read on a later poll, whole.
func TestALineStillBeingWrittenIsLeftForLater(t *testing.T) {
	projects := write(t, snapshotLine)
	path := filepath.Join(projects, "-w-sessions-bold-otter-3f9a7k-oppenheimer", conversation+".jsonl")
	file, err := os.OpenFile(path, os.O_APPEND|os.O_WRONLY, 0)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := file.WriteString(promptLine[:len(promptLine)/2]); err != nil {
		t.Fatal(err)
	}
	if err := file.Close(); err != nil {
		t.Fatal(err)
	}
	if got := firstPrompt(projects); got != "" {
		t.Fatalf("first prompt = %q, want none until the line is whole", got)
	}
}

// A conversation found in two folders (a Claude Code version that encodes the
// working directory differently) is read from the one written last, whatever
// order the folders are listed in.
func TestAConversationInTwoFoldersIsReadFromTheNewest(t *testing.T) {
	projects := write(t, `{"type":"user","message":{"role":"user","content":"the older folder"}}`)
	older := filepath.Join(projects, "-w-sessions-bold-otter-3f9a7k-oppenheimer", conversation+".jsonl")
	newer := filepath.Join(projects, "-z-renamed-folder", conversation+".jsonl")
	if err := os.MkdirAll(filepath.Dir(newer), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(newer, []byte(promptLine+"\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	past := time.Now().Add(-time.Hour)
	if err := os.Chtimes(older, past, past); err != nil {
		t.Fatal(err)
	}
	if got, want := firstPrompt(projects), "Fix the repo picker so it lists archived repos"; got != want {
		t.Fatalf("first prompt = %q, want the newest folder's %q", got, want)
	}
}

func TestNoTranscriptIsNoPrompt(t *testing.T) {
	if got := firstPrompt(t.TempDir()); got != "" {
		t.Fatalf("first prompt = %q, want none", got)
	}
}

// The conversation name is joined into a glob, so only a UUID's characters
// are ever looked up, and an agent whose transcript this does not read gets
// nothing rather than Claude Code's.
func TestOnlyAClaudeConversationIsLookedUp(t *testing.T) {
	projects := write(t, promptLine)
	reader := transcript.New(transcript.Options{ClaudeProjects: projects})
	if got := reader.FirstPrompt(domain.AgentClaude, "*"); got != "" {
		t.Fatalf("a wildcard conversation read %q", got)
	}
	if got := reader.FirstPrompt(domain.AgentCodex, conversation); got != "" {
		t.Fatalf("a Codex session read Claude Code's transcript: %q", got)
	}
}
