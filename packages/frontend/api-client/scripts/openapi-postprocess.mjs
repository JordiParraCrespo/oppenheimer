import { execSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const apiServicesFolder = path.resolve(__dirname, '../src/data-access/api/openapi');
const commonDir = path.resolve(__dirname, '../src/common');
const destModelsDir = path.resolve(commonDir, 'models');
const indexFilePath = path.join(apiServicesFolder, 'index.ts');
const commonIndexPath = path.join(commonDir, 'index.ts');
const generatedTypesPath = path.resolve(__dirname, '../src/generated/types.gen.ts');

const BANNER = '/* Auto-generated by openapi-postprocess -- do not edit */';

/**
 * One generator owns every DTO name.
 *
 * `src/common/models/` was emitted by openapi-typescript-codegen, which is
 * retired: `openapi-ts` now writes the whole surface to `src/generated/`. Two
 * hand-maintained definitions of the same name silently drift — a DTO gains a
 * property in the API and only the hey-api copy learns about it, while
 * consumers that import the name from this package keep the stale shape. So
 * every legacy file whose type also exists in the hey-api output is rewritten
 * to a re-export of it, leaving one definition per name.
 *
 * A name that exists only here belongs to an endpoint the API no longer
 * exposes. It keeps its own definition and is reported rather than failing the
 * build; delete it, with its schema and service, alongside the endpoint — the
 * console slice replaces this layer.
 */
function reexportLegacyModels() {
  if (!fs.existsSync(destModelsDir)) return;

  if (!fs.existsSync(generatedTypesPath)) {
    console.warn(
      `⚠️  No hey-api types at ${generatedTypesPath}. Leaving src/common/models untouched.`,
    );
    return;
  }

  const generated = fs.readFileSync(generatedTypesPath, 'utf8');
  const generatedNames = new Set(
    Array.from(generated.matchAll(/^export type (\w+)\b/gm), (m) => m[1]),
  );

  const specifier = path
    .relative(destModelsDir, generatedTypesPath)
    .replace(/\\/g, '/')
    .replace(/\.ts$/, '');

  const orphans = [];
  let rewritten = 0;

  for (const filename of fs.readdirSync(destModelsDir).sort()) {
    if (!filename.endsWith('.ts')) continue;
    const name = path.basename(filename, '.ts');

    if (!generatedNames.has(name)) {
      orphans.push(name);
      continue;
    }

    const fullPath = path.join(destModelsDir, filename);
    const contents = `${BANNER}\nexport type { ${name} } from '${specifier}';\n`;
    if (fs.readFileSync(fullPath, 'utf8') !== contents) {
      fs.writeFileSync(fullPath, contents);
      rewritten += 1;
    }
  }

  console.log(
    `🔁  ${rewritten} legacy model file(s) rewritten to re-export ${path.basename(generatedTypesPath)}`,
  );

  if (orphans.length > 0) {
    console.warn(
      `⚠️  ${orphans.length} legacy model(s) have no hey-api counterpart and keep their own definition:\n` +
        orphans.map((name) => `      - ${name}`).join('\n') +
        '\n    They are not in apps/api/openapi.json, so nothing regenerates them.',
    );
  }
}

/**
 * Fix import paths in generated service files so they reference
 * the models from their new location in src/common/models.
 */
function fixImports() {
  const servicesDir = path.resolve(apiServicesFolder, 'services');
  if (!fs.existsSync(servicesDir)) {
    console.warn('⚠️  Services directory not found. Skipping import fixes.');
    return;
  }

  const filenames = fs.readdirSync(servicesDir);
  for (const filename of filenames) {
    const fullPath = path.join(servicesDir, filename);
    if (!fs.lstatSync(fullPath).isFile()) continue;

    const src = fs.readFileSync(fullPath, 'utf8');
    const dst = src.replace(/(['"])(?:\.\.\/)+models\//g, '$1../../../../common/models/');

    if (dst !== src) {
      fs.writeFileSync(fullPath, dst);
      console.log(`🔧  Fixed imports in ${filename}`);
    }
  }
}

/**
 * Generate a barrel index file at src/common/index.ts that
 * re-exports every model type.
 */
function generateCommonIndex() {
  if (!fs.existsSync(destModelsDir)) {
    console.warn('⚠️  No models found to index. Skipping common index generation.');
    return;
  }

  const modelFiles = fs.readdirSync(destModelsDir).filter((f) => f.endsWith('.ts'));

  const exports = modelFiles
    .map((f) => path.basename(f, '.ts'))
    .sort()
    .map((name) => `export type { ${name} } from "./models/${name}";`)
    .join('\n');

  fs.writeFileSync(commonIndexPath, `${BANNER}\n${exports}\n`);
  console.log(`📄  Created ${path.relative(process.cwd(), commonIndexPath)}`);
}

/**
 * Remove model re-exports from the OpenAPI index.ts so consumers
 * import models from src/common instead.
 */
function cleanIndexExports() {
  if (!fs.existsSync(indexFilePath)) {
    console.warn(`⚠️  index.ts not found at ${indexFilePath}. Skipping export cleanup.`);
    return;
  }

  const lines = fs.readFileSync(indexFilePath, 'utf8').split(/\r?\n/);
  const filtered = lines.filter(
    (l) => !/^export\s+(?:type\s+)?\{[^}]*\}\s+from\s+['"]\.\/models\//.test(l.trim()),
  );

  if (filtered.length !== lines.length) {
    fs.writeFileSync(indexFilePath, filtered.join('\n'));
    console.log('🧹  Removed model exports from index.ts');
  }
}

/**
 * Generate a barrel index at services/index.ts re-exporting all service classes.
 */
function generateServicesIndex() {
  const servicesDir = path.resolve(apiServicesFolder, 'services');
  if (!fs.existsSync(servicesDir)) return;

  const serviceFiles = fs
    .readdirSync(servicesDir)
    .filter((f) => f.endsWith('.ts') && f !== 'index.ts');
  const exports = serviceFiles
    .map((f) => path.basename(f, '.ts'))
    .sort()
    .map((name) => `export { ${name} } from './${name}';`)
    .join('\n');

  fs.writeFileSync(path.join(servicesDir, 'index.ts'), `${BANNER}\n${exports}\n`);
  console.log('📄  Created services/index.ts');
}

/**
 * Generate the root src/index.ts barrel that re-exports core, services, and models.
 */
function generateRootIndex() {
  const rootIndexPath = path.resolve(__dirname, '../src/index.ts');

  const servicesDir = path.resolve(apiServicesFolder, 'services');
  const serviceFiles = fs.existsSync(servicesDir)
    ? fs.readdirSync(servicesDir).filter((f) => f.endsWith('.ts') && f !== 'index.ts')
    : [];

  const modelFiles = fs.existsSync(destModelsDir)
    ? fs.readdirSync(destModelsDir).filter((f) => f.endsWith('.ts'))
    : [];

  // DTOs only the hey-api output defines. Endpoints the retired generator
  // never covered (hosts, installations) have no file in `src/common/models`,
  // so without this a consumer reaching for their shapes has to hand-write
  // one — which is how `HostsRepository` came to read `state` for a field the
  // API sends as `online`, uncaught until something finally called it.
  //
  // Exported by name rather than as a namespace: a `export type * as` re-export
  // does not survive the consumer's build, and the failure is silent — the
  // member resolves to something unusable rather than erroring at the import.
  const legacyNames = new Set(modelFiles.map((f) => path.basename(f, '.ts')));
  const generatedOnly = fs.existsSync(generatedTypesPath)
    ? Array.from(
        new Set(
          Array.from(
            fs.readFileSync(generatedTypesPath, 'utf8').matchAll(/^export type (\w+) =/gm),
            (m) => m[1],
          ),
        ),
      )
        .filter((name) => !legacyNames.has(name) && /(ResponseDto|Request)$/.test(name))
        .sort()
    : [];

  const lines = [
    "export { applyApiClientConfig, getAuthHeaders, rememberHeaders } from './configure';",
    "export type { ApiClientConfig, AuthHeaders } from './configure';",
    "export { client as heyApiClient } from './generated/client.gen';",
    "export * as heyApiQuery from './generated/@tanstack/react-query.gen';",
    "export * as heyApiSdk from './generated/sdk.gen';",
    '',
    BANNER,
    '',
    ...(generatedOnly.length
      ? [
          '// DTOs the hey-api output alone defines',
          `export type {\n${generatedOnly.map((n) => `  ${n},`).join('\n')}\n} from './generated/types.gen';`,
          '',
        ]
      : []),
    '// Core',
    "export { ApiError } from './data-access/api/openapi/core/ApiError';",
    "export { CancelablePromise, CancelError } from './data-access/api/openapi/core/CancelablePromise';",
    "export { OpenAPI } from './data-access/api/openapi/core/OpenAPI';",
    "export type { OpenAPIConfig } from './data-access/api/openapi/core/OpenAPI';",
    '',
    '// Services',
    ...serviceFiles.map((f) => {
      const name = path.basename(f, '.ts');
      return `export { ${name} } from './data-access/api/openapi/services/${name}';`;
    }),
    '',
    '// Models',
    ...modelFiles.map((f) => {
      const name = path.basename(f, '.ts');
      return `export type { ${name} } from './common/models/${name}';`;
    }),
    '',
  ];

  fs.writeFileSync(rootIndexPath, lines.join('\n'));
  console.log(`📄  Created ${path.relative(process.cwd(), rootIndexPath)}`);
}

/**
 * Format all generated and moved files with Biome.
 */
function formatFiles() {
  try {
    const rootIndex = path.resolve(__dirname, '../src/index.ts');
    execSync(`npx biome format --write "${apiServicesFolder}" "${commonDir}" "${rootIndex}"`, {
      stdio: 'inherit',
    });
  } catch (e) {
    console.warn('Formatting skipped (biome not available):', e.message);
  }
}

function main() {
  reexportLegacyModels();
  fixImports();
  generateCommonIndex();
  cleanIndexExports();
  generateServicesIndex();
  generateRootIndex();
  formatFiles();
  console.log('✨  OpenAPI Post-Process Done');
}

main();
