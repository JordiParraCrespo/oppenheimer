import { execSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const generatedTypesPath = path.resolve(__dirname, '../src/generated/types.gen.ts');
const rootIndexPath = path.resolve(__dirname, '../src/index.ts');

const BANNER = '/* Auto-generated by openapi-postprocess -- do not edit */';

/**
 * Write the package's root barrel: the runtime seam (`configure.ts`), the
 * generated SDK, and every request and response DTO the API names, by name.
 * The SDK is the one way to call the API; the generated client under it and
 * any query helpers stay inside the package.
 *
 * One generator owns the whole surface: `openapi-ts` writes `src/generated/`
 * from the API's OpenAPI document. The openapi-typescript-codegen classes that
 * used to sit beside it (`src/data-access/`, `src/common/`) are gone — they
 * covered only the starter's endpoints and drifted from the API.
 *
 * DTOs are exported by name rather than as a namespace: an `export type * as`
 * re-export does not survive the consumer's build, and the failure is silent —
 * the member resolves to something unusable rather than erroring at the import.
 */
function generateRootIndex() {
  const dtoNames = fs.existsSync(generatedTypesPath)
    ? Array.from(
        new Set(
          Array.from(
            fs.readFileSync(generatedTypesPath, 'utf8').matchAll(/^export type (\w+) =/gm),
            (m) => m[1],
          ),
        ),
      )
        .filter((name) => /(Dto|Request)$/.test(name))
        .sort()
    : [];

  const lines = [
    "export { applyApiClientConfig } from './configure';",
    "export type { ApiClientConfig, AuthHeaders } from './configure';",
    "export * as heyApiSdk from './generated/sdk.gen';",
    '',
    BANNER,
    '',
    ...(dtoNames.length
      ? [
          `export type {\n${dtoNames.map((n) => `  ${n},`).join('\n')}\n} from './generated/types.gen';`,
          '',
        ]
      : []),
  ];

  fs.writeFileSync(rootIndexPath, lines.join('\n'));
  console.log(`📄  Created ${path.relative(process.cwd(), rootIndexPath)}`);
}

/**
 * Bring every generated file to what `pnpm check` accepts, so a regeneration
 * with no API change leaves git clean. `check --write`, not `format --write`:
 * the committed files are also import-sorted (Biome's organize-imports
 * assist), and formatting alone leaves that as a diff.
 */
function formatFiles() {
  try {
    const generatedDir = path.resolve(__dirname, '../src/generated');
    execSync(`npx biome check --write "${generatedDir}" "${rootIndexPath}"`, { stdio: 'inherit' });
  } catch (e) {
    console.warn('Formatting skipped (biome not available):', e.message);
  }
}

generateRootIndex();
formatFiles();
console.log('✨  OpenAPI Post-Process Done');
