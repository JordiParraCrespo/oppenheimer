#!/usr/bin/env node
/**
 * Write the runner's launch table from the coding-agent catalog.
 *
 * `packages/shared/src/agents/catalog.ts` is the source 01 points at for how
 * a structured launch becomes each agent's argv. The runner reads the same
 * entry, in Go; rather than a hand-kept twin that drifts on the next catalog
 * edit, the Go file is generated here as part of
 * `pnpm --filter @oppenheimer/shared build` and committed. `catalog.spec.ts`
 * fails when the committed file is stale, so the drift cannot ship green.
 */
const { writeFileSync } = require('node:fs');
const { join, relative } = require('node:path');

const { CODING_AGENTS, CODING_AGENT_IDS } = require('../dist/agents/catalog.js');
const { HOST_TOOLS, HOST_TOOL_IDS } = require('../dist/agents/host-tools.js');
const { AGENT_HOST_SETUP } = require('../dist/agents/host-setup.js');

/** An agent's install and update entry (`host-setup.ts`); none for the blank terminal. */
const setupOf = (id) => AGENT_HOST_SETUP[id] ?? {};

const outputPath = join(
  __dirname,
  '..',
  '..',
  '..',
  'apps',
  'runner',
  'internal',
  'sessions',
  'domain',
  'launch_catalog.gen.go',
);

// The updaters go to the host context, which owns the tools and never imports
// the sessions one (`apps/runner/internal/arch/arch_test.go`).
const updatesOutputPath = join(
  __dirname,
  '..',
  '..',
  '..',
  'apps',
  'runner',
  'internal',
  'host',
  'domain',
  'agent_update.gen.go',
);

// How each tool gets onto a host, for the same host context: the agents'
// and the host tools' `install` entries, the methods an updater is told, and
// the packages a person installs themselves.
const hostToolsOutputPath = join(
  __dirname,
  '..',
  '..',
  '..',
  'apps',
  'runner',
  'internal',
  'host',
  'domain',
  'host_tools.gen.go',
);

function goStrings(vector) {
  return `[]string{${vector.map((word) => JSON.stringify(word)).join(', ')}}`;
}

/** Inside a composite literal `gofmt -s` elides the element type. */
function goElided(vector) {
  return `{${vector.map((word) => JSON.stringify(word)).join(', ')}}`;
}

/**
 * gofmt aligns the values of consecutive single-line `key: value` entries to
 * the widest key of the run; a multi-line value ends the run. Emitting that
 * alignment here is what keeps the committed file identical to a formatted one,
 * so `gofmt -l` stays quiet and the check below compares bytes.
 */
function aligned(entries, indent) {
  const width = Math.max(...entries.map(([key]) => key.length));
  return entries.map(
    ([key, value]) => `${indent}${key}:${' '.repeat(width - key.length + 1)}${value},`,
  );
}

/**
 * A struct literal's fields in order, laid out as gofmt lays them: each run of
 * consecutive single-line fields `aligned`, and a multi-line value (a map)
 * on its own line, ending the run before it.
 */
function fieldLines(fields, indent) {
  const lines = [];
  let run = [];
  const flush = () => {
    if (run.length > 0) lines.push(...aligned(run, indent));
    run = [];
  };
  for (const [key, value] of fields) {
    if (value.includes('\n')) {
      flush();
      lines.push(`${indent}${key}: ${value},`);
    } else {
      run.push([key, value]);
    }
  }
  flush();
  return lines;
}

/** One permission level: its argv and its env, each omitted when empty. */
function goLevel(level) {
  const fields = [];
  if (level.argv.length) fields.push(`argv: ${goStrings(level.argv)}`);
  const env = Object.entries(level.env);
  if (env.length) {
    const pairs = env.map(([name, value]) => `${JSON.stringify(name)}: ${JSON.stringify(value)}`);
    fields.push(`env: map[string]string{${pairs.join(', ')}}`);
  }
  return `{${fields.join(', ')}}`;
}

function goLevels(record) {
  const entries = Object.entries(record).map(([key, level]) => [
    JSON.stringify(key),
    goLevel(level),
  ]);
  return `map[string]launchLevel{\n${aligned(entries, '\t\t\t').join('\n')}\n\t\t}`;
}

/**
 * The effort levels each model offers, keyed by model id: which names a
 * launch on that model may carry. A model with no effort has no row, so the
 * runner drops a level asked of it. How a level is spelled is the agent's one
 * `effort` level, beside this.
 */
function goEffortLevels(models) {
  const rows = models
    .filter((model) => model.effort)
    .map((model) => [JSON.stringify(model.id), goElided(model.effort.levels)]);
  return `map[string][]string{\n${aligned(rows, '\t\t\t').join('\n')}\n\t\t}`;
}

/** One login target: a host, and a path prefix when there is one. */
function goTarget(target) {
  const fields = [`Host: ${JSON.stringify(target.host)}`];
  if (target.path) fields.push(`Path: ${JSON.stringify(target.path)}`);
  return `{${fields.join(', ')}}`;
}

function render() {
  const lines = [
    '// Code generated by packages/shared/scripts/emit-agent-catalog.cjs from',
    '// packages/shared/src/agents/catalog.ts; DO NOT EDIT.',
    '',
    'package domain',
    '',
    "// launchCatalog is each agent's `launch` entry of the catalog, and the effort",
    '// levels its models offer: the argument vectors a structured launch becomes.',
    '// `<model>`, `<prompt>`, `<conversation>` and `<teleport>` are substituted',
    '// whole; an effort spelling has `<effort>` and `<model>` replaced inside',
    '// each word.',
    'var launchCatalog = map[string]launchMap{',
  ];
  for (const id of CODING_AGENT_IDS) {
    const agent = CODING_AGENTS[id];
    const launch = agent.launch;
    lines.push(`\t${JSON.stringify(id)}: {`);
    // Every field in its order, as data; `fieldLines` lays them out the one
    // way gofmt does, so no shape of entry needs a branch of its own here.
    const fields = [['command', JSON.stringify(agent.command)]];
    if (launch.always) fields.push(['always', goStrings(launch.always)]);
    if (launch.model) fields.push(['model', goStrings(launch.model)]);
    const defaultModel = agent.models.find((model) => model.default);
    if (defaultModel) fields.push(['defaultModel', JSON.stringify(defaultModel.id)]);
    if (launch.permission) fields.push(['permission', goLevels(launch.permission)]);
    if (launch.effort) {
      fields.push(['effort', `launchLevel${goLevel(launch.effort)}`]);
      if (launch.effort.unset) fields.push(['effortUnset', JSON.stringify(launch.effort.unset)]);
      fields.push(['effortLevels', goEffortLevels(agent.models)]);
    }
    if (launch.prompt) fields.push(['prompt', goStrings(launch.prompt)]);
    if (launch.conversation?.create) {
      fields.push(['conversationCreate', goStrings(launch.conversation.create)]);
    }
    if (launch.conversation?.resume) {
      fields.push(['conversationResume', goStrings(launch.conversation.resume)]);
    }
    if (launch.conversation?.resumeLeads) fields.push(['conversationResumeLeads', 'true']);
    if (launch.teleport) {
      fields.push(['teleportStart', goStrings(launch.teleport.start)]);
      fields.push(['teleportResume', goStrings(launch.teleport.resume)]);
    }
    lines.push(...fieldLines(fields, '\t\t'));
    lines.push('\t},');
  }
  lines.push('}', '');
  // The runner's vendor-login allowlist, per agent. An agent with no targets
  // (the blank terminal) has no row, so nothing on its screen is a login.
  lines.push(
    "// loginTargets is each agent's `loginTargets` entry of the catalog: the",
    '// vendor logins its screen may show that become a button. Hosts are',
    '// compared for equality and a path, when set, must prefix the URL path.',
    'var loginTargets = map[string][]LoginTarget{',
  );
  const targets = CODING_AGENT_IDS.filter((id) => CODING_AGENTS[id].loginTargets).map((id) => [
    JSON.stringify(id),
    `{${CODING_AGENTS[id].loginTargets.map(goTarget).join(', ')}}`,
  ]);
  lines.push(...aligned(targets, '\t'), '}', '');
  // How a message is typed into each agent; the plain terminal has no row.
  lines.push(
    "// inputCatalog is each agent's `input` entry of the catalog: the keys that",
    '// send and interrupt a message typed into it, and the pause between a',
    '// paste and its submit, in milliseconds.',
    'var inputCatalog = map[string]agentInput{',
  );
  const inputs = CODING_AGENT_IDS.filter((id) => CODING_AGENTS[id].input).map((id) => {
    const input = CODING_AGENTS[id].input;
    return [
      JSON.stringify(id),
      `{submit: ${JSON.stringify(input.submit)}, stop: ${JSON.stringify(input.stop)}, pasteGapMs: ${input.pasteGapMs}}`,
    ];
  });
  lines.push(...aligned(inputs, '\t'), '}', '');
  return lines.join('\n');
}

/**
 * Each agent's `update` argv, keyed by the executable it runs on — the tool
 * name the host context probes. The blank terminal has no command and no
 * updater, so it has no row.
 */
function renderUpdates() {
  const rows = CODING_AGENT_IDS.filter((id) => setupOf(id).update).map((id) => [
    JSON.stringify(CODING_AGENTS[id].command),
    goElided(setupOf(id).update),
  ]);
  return [
    '// Code generated by packages/shared/scripts/emit-agent-catalog.cjs from',
    '// packages/shared/src/agents/catalog.ts; DO NOT EDIT.',
    '',
    'package domain',
    '',
    "// agentUpdates is each agent's `update` entry of the catalog, keyed by the",
    '// executable it runs on: the argv, appended to that executable, that updates',
    '// the CLI in place without asking. An agent whose updater asks has no row.',
    'var agentUpdates = map[string][]string{',
    ...aligned(rows, '\t'),
    '}',
    '',
  ].join('\n');
}

/** `~/.local/bin` → `.local/bin`: the runner joins it to the home it finds. */
function homeRelative(dir) {
  if (!dir.startsWith('~/')) throw new Error(`install bin ${dir} is not ~-relative`);
  return dir.slice(2);
}

/**
 * Every installable tool keyed by the executable it puts on PATH: agents by
 * their `command`, host tools by theirs. A command that both would claim is a
 * catalog error, not a choice to make here.
 */
function installables() {
  const rows = [];
  for (const id of CODING_AGENT_IDS) {
    const { install } = setupOf(id);
    if (install) rows.push({ command: CODING_AGENTS[id].command, kind: 'agent', install });
  }
  for (const id of HOST_TOOL_IDS) {
    const tool = HOST_TOOLS[id];
    if (tool.install) rows.push({ command: tool.command, kind: 'tool', install: tool.install });
  }
  const seen = new Set();
  for (const row of rows) {
    if (seen.has(row.command)) throw new Error(`two catalog entries install ${row.command}`);
    seen.add(row.command);
  }
  return rows;
}

function renderHostTools() {
  const lines = [
    '// Code generated by packages/shared/scripts/emit-agent-catalog.cjs from',
    '// packages/shared/src/agents/catalog.ts and host-tools.ts; DO NOT EDIT.',
    '',
    'package domain',
    '',
    '// toolInstalls is every `install` entry of the catalogs, keyed by the',
    '// executable it puts on PATH: the sh script per platform family, run as the',
    '// person with no terminal, and the home-relative directory it leaves the',
    '// executable in.',
    'var toolInstalls = map[string]toolInstall{',
  ];
  for (const row of installables()) {
    lines.push(`\t${JSON.stringify(row.command)}: {`);
    const fields = [['kind', JSON.stringify(row.kind)]];
    if (row.install.macos) fields.push(['macos', JSON.stringify(row.install.macos)]);
    if (row.install.linux) fields.push(['linux', JSON.stringify(row.install.linux)]);
    fields.push(['bin', JSON.stringify(homeRelative(row.install.bin))]);
    lines.push(...aligned(fields, '\t\t'));
    lines.push('\t},');
  }
  lines.push('}', '');

  // The catalog ids an install may be asked for by, where they are not the
  // executable itself (`claude-code` is `claude`), so the console's names and
  // the CLI's resolve to the one key the table above uses.
  lines.push(
    '// installAliases maps an agent catalog id to the executable the install',
    '// table is keyed by, where the two differ.',
    'var installAliases = map[string]string{',
  );
  const aliases = CODING_AGENT_IDS.filter(
    (id) => setupOf(id).install && CODING_AGENTS[id].command !== id,
  ).map((id) => [JSON.stringify(id), JSON.stringify(CODING_AGENTS[id].command)]);
  lines.push(...aligned(aliases, '\t'), '}', '');

  lines.push(
    "// updateMethods is each agent's `updateMethods` entry, keyed by its",
    '// executable: what `<method>` in its updater is, by where the executable',
    '// really lives. The first entry whose fragment the resolved path contains wins.',
    'var updateMethods = map[string][]installMethod{',
  );
  for (const id of CODING_AGENT_IDS) {
    const { updateMethods } = setupOf(id);
    if (!updateMethods) continue;
    lines.push(`\t${JSON.stringify(CODING_AGENTS[id].command)}: {`);
    for (const m of updateMethods) {
      lines.push(
        `\t\t{method: ${JSON.stringify(m.method)}, pathContains: ${JSON.stringify(m.pathContains)}},`,
      );
    }
    lines.push('\t},');
  }
  lines.push('}', '');

  lines.push(
    '// packageInstalls is each host tool the person installs with the package',
    '// manager, and the package that provides it under each.',
    'var packageInstalls = map[string]packageNames{',
  );
  const packaged = HOST_TOOL_IDS.filter((id) => HOST_TOOLS[id].packages).map((id) => [
    JSON.stringify(HOST_TOOLS[id].command),
    `{brew: ${JSON.stringify(HOST_TOOLS[id].packages.brew)}, apt: ${JSON.stringify(HOST_TOOLS[id].packages.apt)}}`,
  ]);
  lines.push(...aligned(packaged, '\t'), '}', '');
  return lines.join('\n');
}

// Only when run: `require()` must not rewrite the committed file, or the spec
// that compares it with render() would compare a fresh render with itself.
if (require.main === module) {
  const outputs = [
    [outputPath, render()],
    [updatesOutputPath, renderUpdates()],
    [hostToolsOutputPath, renderHostTools()],
  ];
  if (process.argv.includes('--check')) {
    const { readFileSync } = require('node:fs');
    let stale = false;
    for (const [path, output] of outputs) {
      if (readFileSync(path, 'utf8') !== output) {
        console.error(
          `${relative(process.cwd(), path)} is stale; run pnpm --filter @oppenheimer/shared build`,
        );
        stale = true;
      }
    }
    process.exit(stale ? 1 : 0);
  }
  for (const [path, output] of outputs) {
    writeFileSync(path, output, 'utf8');
    console.log(`runner agent catalog written to ${relative(process.cwd(), path)}`);
  }
}

module.exports = {
  render,
  outputPath,
  renderUpdates,
  updatesOutputPath,
  renderHostTools,
  hostToolsOutputPath,
};
