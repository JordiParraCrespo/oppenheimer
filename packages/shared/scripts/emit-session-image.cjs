#!/usr/bin/env node
/**
 * Write the runner's image table from the shared one.
 *
 * `src/protocol/session-image.ts` decides what an image a session can take is.
 * The runner re-checks the bytes it pulls in Go; rather than a hand-kept twin
 * of the magic bytes, the table is generated here as part of
 * `pnpm --filter @oppenheimer/shared build` and committed.
 * `session-image.spec.ts` fails when the committed file is stale.
 */
const { writeFileSync } = require('node:fs');
const { join, relative } = require('node:path');

const {
  SESSION_IMAGE_TYPES,
  SESSION_IMAGE_MAX_BYTES,
} = require('../dist/protocol/session-image.js');

const outputPath = join(
  __dirname,
  '..',
  '..',
  '..',
  'apps',
  'runner',
  'internal',
  'sessions',
  'domain',
  'session_image.gen.go',
);

const hex = (bytes) => bytes.map((b) => `0x${b.toString(16).padStart(2, '0')}`).join(', ');

function render() {
  const types = SESSION_IMAGE_TYPES.flatMap((type) => [
    '\t{',
    `\t\tMediaType: ${JSON.stringify(type.mediaType)},`,
    `\t\tExtension: ${JSON.stringify(type.extension)},`,
    '\t\tSignatures: [][]imageSignaturePart{',
    ...type.signatures.map(
      (signature) =>
        `\t\t\t{${signature.map((part) => `{Offset: ${part.offset}, Bytes: []byte{${hex(part.bytes)}}}`).join(', ')}},`,
    ),
    '\t\t},',
    '\t},',
  ]);
  return [
    '// Code generated by packages/shared/scripts/emit-session-image.cjs from',
    '// packages/shared/src/protocol/session-image.ts; DO NOT EDIT.',
    '',
    'package domain',
    '',
    '// ImageMaxBytes is the largest image a session takes.',
    `const ImageMaxBytes = ${SESSION_IMAGE_MAX_BYTES}`,
    '',
    '// imageTypes is what counts as an image, in the order they are tried.',
    'var imageTypes = []imageType{',
    ...types,
    '}',
    '',
  ].join('\n');
}

const output = render();
if (process.argv.includes('--check')) {
  const { readFileSync } = require('node:fs');
  if (readFileSync(outputPath, 'utf8') !== output) {
    console.error(
      `${relative(process.cwd(), outputPath)} is stale; run pnpm --filter @oppenheimer/shared build`,
    );
    process.exit(1);
  }
  process.exit(0);
}
writeFileSync(outputPath, output, 'utf8');
console.log(`runner image table written to ${relative(process.cwd(), outputPath)}`);

module.exports = { render, outputPath };
