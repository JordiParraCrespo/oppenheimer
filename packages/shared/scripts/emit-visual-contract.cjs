#!/usr/bin/env node
/**
 * Write the runner's visual contract from the shared schema.
 *
 * `src/schemas/visual.schema.ts` decides what a visual is. The runner checks a
 * spec's shape before it keeps one (`runner sessions show`), so the agent hears
 * of a fault at once; rather than a hand-kept twin of the block types and
 * their required fields, they are read off the schema here, as part of
 * `pnpm --filter @oppenheimer/shared build`, and committed.
 * `visual.schema.spec.ts` fails when the committed file is stale. The rules
 * between fields (a value per label, under zero) stay the console's: it parses
 * every spec with the schema itself.
 */
const { writeFileSync } = require('node:fs');
const { join, relative } = require('node:path');

const {
  visualSchema,
  visualBlockTypes,
  VISUAL_BLOCKS_MAX,
  VISUAL_BYTES_MAX,
} = require('../dist/schemas/visual.schema.js');

const outputPath = join(
  __dirname,
  '..',
  '..',
  '..',
  'apps',
  'runner',
  'internal',
  'sessions',
  'adapters',
  'transcript',
  'visual_contract.gen.go',
);

/** Each block type's fields that are not optional, but `type`, read off its object schema. */
function requiredFields() {
  const object = visualSchema._def.schema ?? visualSchema;
  const blocks = object.shape.blocks._def.type;
  const required = {};
  for (const option of blocks.options) {
    const type = option.shape.type.value;
    required[type] = Object.entries(option.shape)
      .filter(([name, field]) => name !== 'type' && !field.isOptional())
      .map(([name]) => name);
  }
  return required;
}

function render() {
  const required = requiredFields();
  const missing = visualBlockTypes.filter((type) => !(type in required));
  if (missing.length > 0) throw new Error(`no schema for block types: ${missing.join(', ')}`);
  const width = Math.max(...visualBlockTypes.map((type) => JSON.stringify(type).length + 1));
  return [
    '// Code generated by packages/shared/scripts/emit-visual-contract.cjs from',
    '// packages/shared/src/schemas/visual.schema.ts; DO NOT EDIT.',
    '',
    'package transcript',
    '',
    "// VisualSpecMax bounds a visual's spec, in bytes of its JSON.",
    `const VisualSpecMax = ${VISUAL_BYTES_MAX}`,
    '',
    '// visualBlocksMax is the most blocks one visual holds.',
    `const visualBlocksMax = ${VISUAL_BLOCKS_MAX}`,
    '',
    '// visualBlockTypes are the block types the console draws, in the order the tools teach them.',
    'var visualBlockTypes = []string{',
    ...visualBlockTypes.map((type) => `\t${JSON.stringify(type)},`),
    '}',
    '',
    '// visualRequired names, for each block type, the fields it cannot draw without.',
    'var visualRequired = map[string][]string{',
    ...visualBlockTypes.map(
      (type) =>
        `\t${`${JSON.stringify(type)}:`.padEnd(width)} {${required[type].map((name) => JSON.stringify(name)).join(', ')}},`,
    ),
    '}',
    '',
  ].join('\n');
}

// Only when run: `require()` must not rewrite the committed file, or the spec
// that compares it with render() would compare a fresh render with itself.
if (require.main === module) {
  const check = process.argv.includes('--check');
  const { readFileSync } = require('node:fs');
  const next = render();
  if (check) {
    const current = readFileSync(outputPath, 'utf8');
    if (current !== next) {
      console.error(
        `${relative(process.cwd(), outputPath)} is stale: run pnpm --filter @oppenheimer/shared build`,
      );
      process.exit(1);
    }
  } else {
    writeFileSync(outputPath, next);
    console.log(`wrote ${relative(process.cwd(), outputPath)}`);
  }
}

module.exports = { outputPath, render };
