#!/usr/bin/env node
/**
 * Write the runner's file table from the shared one.
 *
 * `src/protocol/session-file.ts` decides what a file a session can take is.
 * The runner re-checks the bytes it pulls in Go; rather than a hand-kept twin
 * of the magic bytes and the text rules, the table is generated here as part of
 * `pnpm --filter @oppenheimer/shared build` and committed.
 * `session-file.spec.ts` fails when the committed file is stale.
 */
const { writeFileSync } = require('node:fs');
const { join, relative } = require('node:path');

const {
  SESSION_FILE_TYPES,
  SESSION_TEXT_TYPES,
  SESSION_TEXT_REFUSED_OPENINGS,
  SESSION_TEXT_CONTROL_ALLOWED,
  SESSION_TEXT_OPENING_BYTES,
  SESSION_FILE_MAX_BYTES,
  SESSION_CREATE_MAX_FILES,
  sessionFileIs,
} = require('../dist/protocol/session-file.js');
const { SESSION_FILE_VECTORS, vectorBytes } = require('../dist/protocol/session-file.vectors.js');

const outputPath = join(
  __dirname,
  '..',
  '..',
  '..',
  'apps',
  'runner',
  'internal',
  'sessions',
  'domain',
  'session_file.gen.go',
);
const vectorsPath = outputPath.replace(
  /session_file\.gen\.go$/,
  'session_file_vectors_gen_test.go',
);

const hex = (bytes) => bytes.map((b) => `0x${b.toString(16).padStart(2, '0')}`).join(', ');

function render() {
  const types = SESSION_FILE_TYPES.flatMap((type) => [
    '\t{',
    `\t\tMediaType: ${JSON.stringify(type.mediaType)},`,
    `\t\tExtension: ${JSON.stringify(type.extension)},`,
    '\t\tSignatures: [][]signaturePart{',
    ...type.signatures.map(
      (signature) =>
        `\t\t\t{${signature.map((part) => `{Offset: ${part.offset}, Bytes: []byte{${hex(part.bytes)}}}`).join(', ')}},`,
    ),
    '\t\t},',
    '\t},',
  ]);
  const texts = SESSION_TEXT_TYPES.map(
    (type) =>
      `\t{MediaType: ${JSON.stringify(type.mediaType)}, Extension: ${JSON.stringify(type.extension)}},`,
  );
  return [
    '// Code generated by packages/shared/scripts/emit-session-file.cjs from',
    '// packages/shared/src/protocol/session-file.ts; DO NOT EDIT.',
    '',
    'package domain',
    '',
    '// FileMaxBytes is the largest file a session takes.',
    `const FileMaxBytes = ${SESSION_FILE_MAX_BYTES}`,
    '',
    "// CreateMaxFiles is how many files a session's first task may carry.",
    `const CreateMaxFiles = ${SESSION_CREATE_MAX_FILES}`,
    '',
    '// fileTypes are the binary types, known by their magic bytes, in the order they are tried.',
    'var fileTypes = []fileType{',
    ...types,
    '}',
    '',
    '// textTypes are the types text is saved as; the first is the default.',
    'var textTypes = []textType{',
    ...texts,
    '}',
    '',
    '// textControlAllowed are the only control bytes text may hold.',
    `var textControlAllowed = []byte{${hex(SESSION_TEXT_CONTROL_ALLOWED)}}`,
    '',
    '// textOpeningBytes is how many bytes of an opening are compared.',
    `const textOpeningBytes = ${SESSION_TEXT_OPENING_BYTES}`,
    '',
    '// textRefusedOpenings make text a program rather than a document.',
    'var textRefusedOpenings = []string{',
    ...SESSION_TEXT_REFUSED_OPENINGS.map((opening) => `\t${JSON.stringify(opening)},`),
    '}',
    '',
  ].join('\n');
}

/** The vectors with the shared verdict on each, as a Go test the runner must pass. */
function renderVectors() {
  const cases = SESSION_FILE_VECTORS.map((vector) => {
    const bytes = [...vectorBytes(vector)];
    const want = sessionFileIs(vectorBytes(vector), vector.mediaType);
    return `\t{${JSON.stringify(vector.name)}, ${JSON.stringify(vector.mediaType)}, []byte{${hex(bytes)}}, ${want}},`;
  });
  return [
    '// Code generated by packages/shared/scripts/emit-session-file.cjs from',
    '// packages/shared/src/protocol/session-file.vectors.ts; DO NOT EDIT.',
    '',
    'package domain',
    '',
    'import "testing"',
    '',
    '// The verdict sessionFileIs gave each vector in TypeScript, which FileIs',
    '// must give in Go: the text rule has one owner, and this is its check.',
    'var sharedFileVectors = []struct {',
    '\tname      string',
    '\tmediaType string',
    '\tdata      []byte',
    '\twant      bool',
    '}{',
    ...cases,
    '}',
    '',
    'func TestFileIsAgreesWithTheSharedVerdict(t *testing.T) {',
    '\tfor _, v := range sharedFileVectors {',
    '\t\tif got := FileIs(v.data, v.mediaType); got != v.want {',
    '\t\t\tt.Errorf("%s: FileIs = %v, the shared rule says %v", v.name, got, v.want)',
    '\t\t}',
    '\t}',
    '}',
    '',
  ].join('\n');
}

// Only when run: `require()` must not rewrite the committed file, or the spec
// that compares it with render() would compare a fresh render with itself.
if (require.main === module) {
  const outputs = [
    [outputPath, render()],
    [vectorsPath, renderVectors()],
  ];
  if (process.argv.includes('--check')) {
    const { readFileSync } = require('node:fs');
    for (const [path, output] of outputs) {
      if (readFileSync(path, 'utf8') !== output) {
        console.error(
          `${relative(process.cwd(), path)} is stale; run pnpm --filter @oppenheimer/shared build`,
        );
        process.exit(1);
      }
    }
    process.exit(0);
  }
  for (const [path, output] of outputs) writeFileSync(path, output, 'utf8');
  console.log(`runner file table written to ${relative(process.cwd(), outputPath)}`);
}

module.exports = { render, renderVectors, outputPath, vectorsPath };
