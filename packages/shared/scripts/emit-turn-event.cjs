#!/usr/bin/env node
/**
 * Write the runner's `turn.ended` payload from the shared schema.
 *
 * `src/protocol/turn-event.ts` is the source for what a runner logs when a
 * headless turn's agent exits. The runner writes it in Go; the struct is
 * generated here as part of `pnpm --filter @oppenheimer/shared build`, like
 * `session.step`, and committed. `turn-event.spec.ts` fails when the committed
 * file is stale, and when FIELDS no longer names every key of the schema.
 */
const { writeFileSync } = require('node:fs');
const { join, relative } = require('node:path');

const { TURN_ENDED_EVENT_KIND } = require('../dist/protocol/turn-event.js');

const outputPath = join(
  __dirname,
  '..',
  '..',
  '..',
  'apps',
  'runner',
  'internal',
  'link',
  'turn_event.gen.go',
);

/**
 * One row per key of `turnEndedPayloadSchema`, in its order: the JSON name and
 * the Go type. Optional keys are pointers with `omitempty`, so an unknown value
 * is absent on the wire rather than a zero the control plane would store.
 */
const FIELDS = [
  ['exitCode', 'int'],
  ['agentSessionId', '*string'],
  ['result', '*string'],
  ['costUsd', '*float64'],
  ['permissionDenials', '*int'],
  ['outputRef', '*string'],
  ['model', '*string'],
  ['inputTokens', '*int64'],
  ['outputTokens', '*int64'],
  ['cacheReadTokens', '*int64'],
  ['cacheWriteTokens', '*int64'],
];

/** Go's initialisms, so the generated names read like the hand-written ones. */
const goName = (json) =>
  (json[0].toUpperCase() + json.slice(1)).replace(/Id$/, 'ID').replace(/Usd$/, 'USD');

function render() {
  const names = FIELDS.map(([json]) => goName(json));
  const nameWidth = Math.max(...names.map((n) => n.length));
  const typeWidth = Math.max(...FIELDS.map(([, type]) => type.length));
  const lines = FIELDS.map(([json, type], i) => {
    const tag = type.startsWith('*') ? `json:"${json},omitempty"` : `json:"${json}"`;
    return `\t${names[i].padEnd(nameWidth)} ${type.padEnd(typeWidth)} \`${tag}\``;
  });
  return [
    '// Code generated by packages/shared/scripts/emit-turn-event.cjs from',
    '// packages/shared/src/protocol/turn-event.ts; DO NOT EDIT.',
    '',
    'package link',
    '',
    "// TurnEndedKind is the event kind a headless turn's exit is logged as.",
    `const TurnEndedKind = ${JSON.stringify(TURN_ENDED_EVENT_KIND)}`,
    '',
    '// TurnEndedPayload is the payload of a TurnEndedKind event. Every field but',
    '// ExitCode is optional: an agent that does not report a value leaves it nil.',
    'type TurnEndedPayload struct {',
    ...lines,
    '}',
    '',
  ].join('\n');
}

// Only when run: `require()` must not rewrite the committed file, or the spec
// that compares it with render() would compare a fresh render with itself.
if (require.main === module) {
  const output = render();
  if (process.argv.includes('--check')) {
    const { readFileSync } = require('node:fs');
    if (readFileSync(outputPath, 'utf8') !== output) {
      console.error(
        `${relative(process.cwd(), outputPath)} is stale; run pnpm --filter @oppenheimer/shared build`,
      );
      process.exit(1);
    }
    process.exit(0);
  }
  writeFileSync(outputPath, output, 'utf8');
  console.log(`runner turn.ended payload written to ${relative(process.cwd(), outputPath)}`);
}

module.exports = { render, outputPath, FIELDS };
