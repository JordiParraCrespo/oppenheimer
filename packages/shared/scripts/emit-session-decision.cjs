#!/usr/bin/env node
/**
 * Write the runner's `agent.decision` payload from the shared schema.
 *
 * `src/schemas/session-decision.schema.ts` is the source for what a runner
 * reports when its agent waits on a person: an `AskUserQuestion` it read off
 * the transcript, or a permission dialog it read off the screen. The runner
 * builds it in Go; the structs and the bounds are generated here as part of
 * `pnpm --filter @oppenheimer/shared build`, like `turn.ended`, and
 * committed. `session-decision.spec.ts` fails when the committed file is
 * stale, and when STRUCTS no longer names every key of the schema.
 */
const { writeFileSync } = require('node:fs');
const { join, relative } = require('node:path');

const {
  AGENT_DECISION_EVENT_KIND,
  DECISION_ANSWERED_EVENT_KIND,
  SESSION_DECISION_LIMITS,
} = require('../dist/schemas/session-decision.schema.js');

const outputPath = join(
  __dirname,
  '..',
  '..',
  '..',
  'apps',
  'runner',
  'internal',
  'sessions',
  'domain',
  'session_decision.gen.go',
);

/**
 * Each struct, its doc line and its fields: the JSON name, the Go name, the
 * Go type and whether it is left out when empty. A nullable text is a pointer
 * the runner leaves out, which the schema reads as null; a field of the other
 * kind of decision is left out when empty.
 */
const STRUCTS = [
  [
    'DecisionQuestionOption',
    'is one answer a question offers.',
    [
      ['label', 'Label', 'string', false],
      ['description', 'Description', '*string', true],
    ],
  ],
  [
    'DecisionQuestion',
    'is one question of an AskUserQuestion call.',
    [
      ['header', 'Header', '*string', true],
      ['question', 'Question', 'string', false],
      ['multiSelect', 'MultiSelect', 'bool', false],
      ['options', 'Options', '[]DecisionQuestionOption', false],
    ],
  ],
  [
    'DecisionPermissionOption',
    "is one option of a permission dialog, in the dialog's order.",
    [['label', 'Label', 'string', false]],
  ],
  [
    'Decision',
    'is what the agent waits on: a question (Questions) or a permission\n// dialog (Title, Detail, Options), by Kind.',
    [
      ['kind', 'Kind', 'DecisionKind', false],
      ['id', 'ID', 'string', false],
      ['questions', 'Questions', '[]DecisionQuestion', true],
      ['title', 'Title', 'string', true],
      ['detail', 'Detail', '*string', true],
      ['options', 'Options', '[]DecisionPermissionOption', true],
    ],
  ],
  [
    'AgentDecisionPayload',
    'is the payload of an AgentDecisionKind event: nil is nothing pending.',
    [['decision', 'Decision', '*Decision', false]],
  ],
];

/** The bounds, by key of SESSION_DECISION_LIMITS, as Go constant names. */
const LIMIT_NAMES = {
  id: 'DecisionIDMax',
  questions: 'DecisionQuestionsMax',
  questionOptions: 'DecisionQuestionOptionsMax',
  header: 'DecisionHeaderMax',
  question: 'DecisionQuestionMax',
  label: 'DecisionLabelMax',
  description: 'DecisionDescriptionMax',
  permissionOptions: 'DecisionPermissionOptionsMax',
  title: 'DecisionTitleMax',
  detail: 'DecisionDetailMax',
  other: 'DecisionOtherMax',
};

/** gofmt aligns a const group's `=` to its widest name. */
function constGroup(entries) {
  const width = Math.max(...entries.map(([name]) => name.length));
  return ['const (', ...entries.map(([name, value]) => `\t${name.padEnd(width)} = ${value}`), ')'];
}

function struct([name, doc, fields]) {
  const nameWidth = Math.max(...fields.map(([, goName]) => goName.length));
  const typeWidth = Math.max(...fields.map(([, , type]) => type.length));
  const lines = fields.map(([json, goName, type, omit]) => {
    const tag = omit ? `json:"${json},omitempty"` : `json:"${json}"`;
    return `\t${goName.padEnd(nameWidth)} ${type.padEnd(typeWidth)} \`${tag}\``;
  });
  return [`// ${name} ${doc}`, `type ${name} struct {`, ...lines, '}'];
}

function render() {
  const missing = Object.keys(SESSION_DECISION_LIMITS).filter((key) => !LIMIT_NAMES[key]);
  if (missing.length) throw new Error(`no Go name for the limits ${missing.join(', ')}`);
  return [
    '// Code generated by packages/shared/scripts/emit-session-decision.cjs from',
    '// packages/shared/src/schemas/session-decision.schema.ts; DO NOT EDIT.',
    '',
    'package domain',
    '',
    '// AgentDecisionKind is the event kind a pending decision is logged as.',
    `const AgentDecisionKind = ${JSON.stringify(AGENT_DECISION_EVENT_KIND)}`,
    '',
    '// DecisionAnsweredKind is the event kind the control plane logs for an answer.',
    `const DecisionAnsweredKind = ${JSON.stringify(DECISION_ANSWERED_EVENT_KIND)}`,
    '',
    '// The bounds of a decision, in characters (bytes here) and items.',
    ...constGroup(
      Object.entries(SESSION_DECISION_LIMITS).map(([key, value]) => [LIMIT_NAMES[key], value]),
    ),
    '',
    '// DecisionKind says which of the two a Decision is.',
    'type DecisionKind string',
    '',
    ...constGroup([
      ['DecisionQuestionKind', 'DecisionKind("question")'],
      ['DecisionPermissionKind', 'DecisionKind("permission")'],
    ]),
    '',
    ...STRUCTS.flatMap((entry) => [...struct(entry), '']),
  ].join('\n');
}

// Only when run: `require()` must not rewrite the committed file, or the spec
// that compares it with render() would compare a fresh render with itself.
if (require.main === module) {
  const output = render();
  if (process.argv.includes('--check')) {
    const { readFileSync } = require('node:fs');
    if (readFileSync(outputPath, 'utf8') !== output) {
      console.error(
        `${relative(process.cwd(), outputPath)} is stale; run pnpm --filter @oppenheimer/shared build`,
      );
      process.exit(1);
    }
    process.exit(0);
  }
  writeFileSync(outputPath, output, 'utf8');
  console.log(`runner agent.decision payload written to ${relative(process.cwd(), outputPath)}`);
}

module.exports = { render, outputPath, STRUCTS };
