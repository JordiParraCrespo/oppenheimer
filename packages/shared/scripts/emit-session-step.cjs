#!/usr/bin/env node
/**
 * Write the runner's `session.step` vocabulary from the shared schema.
 *
 * `src/protocol/session-step.ts` is the source 01 points at for the steps a
 * runner logs while it starts a session. The runner writes them in Go; rather
 * than a hand-kept twin that drifts the first time a step is added, the Go file
 * is generated here as part of `pnpm --filter @oppenheimer/shared build`, like
 * the launch catalog, and committed. `session-step.spec.ts` fails when the
 * committed file is stale.
 */
const { writeFileSync } = require('node:fs');
const { join, relative } = require('node:path');

const {
  SESSION_STEP_EVENT_KIND,
  SESSION_START_STEPS,
  SESSION_STEP_STATUSES,
} = require('../dist/protocol/session-step.js');

const outputPath = join(
  __dirname,
  '..',
  '..',
  '..',
  'apps',
  'runner',
  'internal',
  'link',
  'session_step.gen.go',
);

const exported = (prefix, value) => prefix + value[0].toUpperCase() + value.slice(1);

/** gofmt aligns the type column of a const group to the widest name. */
function constGroup(type, prefix, values) {
  const names = values.map((value) => exported(prefix, value));
  const width = Math.max(...names.map((name) => name.length));
  const lines = values.map(
    (value, i) =>
      `\t${names[i]}${' '.repeat(width - names[i].length + 1)}${type} = ${JSON.stringify(value)}`,
  );
  return ['const (', ...lines, ')'];
}

function render() {
  return [
    '// Code generated by packages/shared/scripts/emit-session-step.cjs from',
    '// packages/shared/src/protocol/session-step.ts; DO NOT EDIT.',
    '',
    'package link',
    '',
    '// SessionStepKind is the event kind a start step is logged as.',
    `const SessionStepKind = ${JSON.stringify(SESSION_STEP_EVENT_KIND)}`,
    '',
    '// SessionStep is one step of starting a session, in the order the host runs them.',
    'type SessionStep string',
    '',
    ...constGroup('SessionStep', 'SessionStep', SESSION_START_STEPS),
    '',
    '// SessionStepStatus is where a step is. A failure is `session.failed`, not a status.',
    'type SessionStepStatus string',
    '',
    ...constGroup('SessionStepStatus', 'SessionStep', SESSION_STEP_STATUSES),
    '',
    '// SessionStepPayload is the payload of a SessionStepKind event.',
    'type SessionStepPayload struct {',
    '\tStep       SessionStep       `json:"step"`',
    '\tStatus     SessionStepStatus `json:"status"`',
    '\tDurationMs *int64            `json:"durationMs,omitempty"`',
    '}',
    '',
  ].join('\n');
}

const output = render();
if (process.argv.includes('--check')) {
  const { readFileSync } = require('node:fs');
  if (readFileSync(outputPath, 'utf8') !== output) {
    console.error(
      `${relative(process.cwd(), outputPath)} is stale; run pnpm --filter @oppenheimer/shared build`,
    );
    process.exit(1);
  }
  process.exit(0);
}
writeFileSync(outputPath, output, 'utf8');
console.log(`runner session.step vocabulary written to ${relative(process.cwd(), outputPath)}`);

module.exports = { render, outputPath };
